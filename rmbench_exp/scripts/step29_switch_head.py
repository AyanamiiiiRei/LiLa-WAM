#!/usr/bin/env python
"""Stage-memory phase 2: train the learned switch head and check it offline, against baselines.

  python scripts/step29_switch_head.py [--task swap_blocks]

Input: step 28 features (artifacts/stage_memory/<task>/switch_features). Trains on the 45
training demos only; the 5 held-out demos are used for the report, never for fitting.
Head: MLP(CLS 1024 + foresight change 1024 + one-hot k) -> P(current stage has ended);
inputs standardised with training mean/std; BCE with positive-class weighting; write if P > 0.5.

Offline checks (expert frames, so only a sanity check; the closed loop decides):
  per-sample: accuracy, balanced accuracy, AUC on train and held-out
  simulated online use on each demo: start with k = 0, walk the chunk starts, write when the
  head fires; report each write's timing error in chunks vs the oracle-equivalent grid end.
  (After an early write the exact memory state was not generated by step 28; the walk then
  uses the k = s(t) sample and the demo is marked "approx".)
  ablations: CLS only, foresight change only (same training), and the TIME baseline
  (write at the training demos' mean grid ends; it ignores the scene).
Outputs (artifacts/stage_memory/<task>/): switch_head.pt (CLS + change), time_trigger.json,
switch_head_report.md
"""

from __future__ import annotations

import json
from pathlib import Path

import _common
import numpy as np
import torch

from rmbench_lila.stages import GRID
from rmbench_lila.triggers import build_head_mlp


def load(dirpath):
    eps = {}
    for f in sorted(Path(dirpath).glob("*.npz")):
        z = np.load(f)
        eps[f.stem] = {k: z[k] for k in z.files}
        eps[f.stem]["split"] = str(z["split"])
    return eps


def features(e, use, n_stages):
    oh = np.eye(n_stages, dtype=np.float32)[np.minimum(e["k"], n_stages - 1)]
    parts = {"cls": e["cls"], "delta": e["delta"]}
    return np.concatenate([parts[u] for u in use] + [oh], axis=1)


def auc(y, p):
    pos, neg = p[y == 1], p[y == 0]
    if not len(pos) or not len(neg):
        return float("nan")
    return float((pos[:, None] > neg[None, :]).mean() + 0.5 * (pos[:, None] == neg[None, :]).mean())


def train_head(X, y, seed=0, steps=400, hidden=256):
    torch.manual_seed(seed)
    mean, std = X.mean(0), X.std(0) + 1e-6
    Xt = torch.from_numpy((X - mean) / std)
    yt = torch.from_numpy(y.astype(np.float32))
    net = build_head_mlp(X.shape[1], hidden)
    opt = torch.optim.AdamW(net.parameters(), lr=1e-3, weight_decay=1e-2)
    pw = torch.tensor((y == 0).sum() / max((y == 1).sum(), 1), dtype=torch.float32)
    lossf = torch.nn.BCEWithLogitsLoss(pos_weight=pw)
    for _ in range(steps):
        net.train()
        idx = torch.randint(0, len(Xt), (512,))
        loss = lossf(net(Xt[idx])[:, 0], yt[idx])
        opt.zero_grad()
        loss.backward()
        opt.step()
    net.eval()
    return net, mean.astype(np.float32), std.astype(np.float32)


def predict(net, mean, std, X):
    with torch.no_grad():
        return torch.sigmoid(net(torch.from_numpy((X - mean) / std))[:, 0]).numpy()


def walk(e, probs, thr, n_stages):
    """Simulated online trigger on one demo -> write times, approx flag."""
    t, k, s = e["t"], e["k"], e["s"]
    lookup = {(int(a), int(b)): i for i, (a, b) in enumerate(zip(t, k))}
    writes, kk, approx = [], 0, False
    for tt in sorted(set(t.tolist())):
        if kk >= n_stages:
            break
        i = lookup.get((tt, kk))
        if i is None:                                   # memory ahead of the true stage
            approx = True
            i = lookup[(tt, int(s[t == tt][0]) if int(s[t == tt][0]) < n_stages else n_stages - 1)]
        if probs[i] > thr:
            writes.append(tt)
            kk += 1
    return writes, approx


def timing(writes, ends):
    """Per stage: error in chunks (write - end) or None if never written."""
    return [((w - g) // GRID if w is not None else None) for w, g in
            zip(list(writes) + [None] * (len(ends) - len(writes)), ends)]


def summarize(errs):
    flat = [x for e in errs for x in e]
    n = len(flat)
    ok = sum(x is not None and abs(x) <= 1 for x in flat)
    early = sum(x is not None and x < -1 for x in flat)
    late = sum(x is not None and x > 1 for x in flat)
    miss = sum(x is None for x in flat)
    return f"{ok}/{n} within +-1 chunk; early >1: {early}; late >1: {late}; never: {miss}"


def main():
    p = _common.parser(__doc__, config=False)
    p.add_argument("--task", default="swap_blocks")
    p.add_argument("--threshold", type=float, default=0.5)
    args = p.parse_args()
    art = Path(f"artifacts/stage_memory/{args.task}")
    eps = load(art / "switch_features")
    if not eps:
        raise SystemExit("no features: run scripts/step28_switch_features.py first")
    n_stages = len(next(iter(eps.values()))["ends"])
    tr = {k: e for k, e in eps.items() if e["split"] == "train"}
    ho = {k: e for k, e in eps.items() if e["split"] == "heldout"}
    lines = [f"# Switch head ({args.task}): {len(tr)} train demos, {len(ho)} held-out demos", ""]

    # TIME baseline: mean grid ends of the training demos (rounded up to the grid)
    mean_ends = np.mean([e["ends"] for e in tr.values()], axis=0)
    time_ends = [int(np.ceil(x / GRID) * GRID) for x in mean_ends]
    (art / "time_trigger.json").write_text(json.dumps({"ends_env_steps": time_ends,
                                                       "source": "mean grid ends of the training demos"}))
    lines += ["| trigger | train: per-sample acc / bal. acc / AUC | held-out: per-sample acc / bal. acc / AUC "
              "| simulated writes, train | simulated writes, held-out |", "|---|---|---|---|---|"]
    tim = {sp: [timing(time_ends, e["ends"]) for e in d.values()] for sp, d in (("train", tr), ("heldout", ho))}
    lines.append(f"| time (no vision) | - | - | {summarize(tim['train'])} | {summarize(tim['heldout'])} |")

    saved = None
    for name, use in (("CLS + foresight change", ("cls", "delta")), ("CLS only", ("cls",)),
                      ("foresight change only", ("delta",))):
        Xtr = np.concatenate([features(e, use, n_stages) for e in tr.values()])
        ytr = np.concatenate([e["label"] for e in tr.values()])
        net, mean, std = train_head(Xtr, ytr)
        cells, sims = [], []
        for d in (tr, ho):
            X = np.concatenate([features(e, use, n_stages) for e in d.values()])
            y = np.concatenate([e["label"] for e in d.values()])
            pr = predict(net, mean, std, X)
            yhat = pr > args.threshold
            bal = 0.5 * ((yhat[y == 1]).mean() + (~yhat[y == 0]).mean())
            cells.append(f"{(yhat == y).mean():.3f} / {bal:.3f} / {auc(y, pr):.3f}")
            errs, n_approx = [], 0
            for e in d.values():
                w, ap = walk(e, predict(net, mean, std, features(e, use, n_stages)), args.threshold, n_stages)
                errs.append(timing(w, e["ends"]))
                n_approx += ap
            sims.append(summarize(errs) + (f" ({n_approx} approx)" if n_approx else ""))
        lines.append(f"| head: {name} | {cells[0]} | {cells[1]} | {sims[0]} | {sims[1]} |")
        if saved is None:
            saved = {"state_dict": net.state_dict(), "mean": mean, "std": std, "in_dim": Xtr.shape[1],
                     "hidden": 256, "n_stages": n_stages, "threshold": args.threshold, "inputs": list(use)}
    torch.save(saved, art / "switch_head.pt")
    lines += ["", "proprio rule: identical to the definition of the boundaries on expert data (0 error by "
              "construction, step 26); it is tested only in the closed loop.",
              f"time trigger ends (env steps): {time_ends}", "",
              "Saved for evaluation: switch_head.pt = head with CLS + foresight change."]
    (art / "switch_head_report.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
